#!/usr/bin/env python3
"""生成 modules/all/all.go —— 把所有模块包副作用 import 进来。

# 为什么需要这个生成器

组件的注册写在各自模块包的 init() 里（modules/<x>/component.go 里的
component.MustRegister）。Go 的 init() 只在**包被 import 时**才会执行，
所以必须有人把这些包 import 进来。

而这个「有人」如果是一份手写的清单（以前是 app.go 里的 8 行 initModule，
后来变成 9 行副作用 import），就回到 M3 想解决的问题上了：新增一个功能
仍然要记得去改某个文件，忘了就静默不生效。

于是把清单变成**生成物**：
  - 加一个模块 = 只加目录和 component.go，不用改任何现存文件；
  - 忘了跑生成 = CI 的 --check 会红，不会一路滑到用户那边。

# 用法

    python scripts/gen_module_imports.py            # 生成/更新 modules/all/all.go
    python scripts/gen_module_imports.py --check    # 只校验是否最新（CI 用）

# 扫描规则

modules/ 下**直接子目录**里存在 component.go 的，就算一个模块包。
modules/all 自身跳过。判定依据是文件名而不是包名 —— 代价是多写一行
生成规则，好处是不需要为了「能被扫描到」在每个包里塞标记。
"""

from __future__ import annotations

import argparse
import pathlib
import sys

MODULE_ROOT = "modules"
OUTPUT = pathlib.Path(MODULE_ROOT) / "all" / "all.go"
PACKAGE = "all"

HEADER = """// Code generated by scripts/gen_module_imports.py; DO NOT EDIT.
//
// 这个文件只有一件事要做：把全部模块包 import 进来，让它们各自的 init()
// 得到执行 —— 组件注册（component.MustRegister）就发生在各包的 init 里。
//
// 为什么是生成物而不是手写清单：手写清单意味着「加一个功能要记得改这里」，
// 忘了就是新功能静默不生效（接口 404、界面里没有），且日志里看不出所以然。
// 现在加模块只加目录，CI 会替你检查这份文件是不是最新的。
//
// 改模块集合后请执行：
//
//	go generate ./...           # 或在仓库根目录跑
//	python scripts/gen_module_imports.py

package %s

import (
""" % PACKAGE

FOOTER = ")\n"


GO_MOD = pathlib.Path("go.mod")


def module_path() -> str:
    """从 go.mod 读出 module 路径，而不是把前缀写死在脚本里。

    写死过一次，代价是改名时 --check 报出一堆「缺少：auth, cert, ...」的
    假故障，看着像模块全丢了；而从 go.mod 读，它自己就是那份真相。
    """
    if not GO_MOD.is_file():
        raise SystemExit("找不到 go.mod，请在仓库根目录执行")
    for line in GO_MOD.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line.startswith("module "):
            return line[len("module ") :].strip()
    raise SystemExit("go.mod 里没有 module 行")


def module_dirs(root: pathlib.Path) -> list[str]:
    """返回模块目录名，稳定排序（生成结果必须可复现）。"""
    base = root / MODULE_ROOT
    if not base.is_dir():
        raise SystemExit(f"找不到 {base}，请在仓库根目录执行")
    names = []
    for child in sorted(base.iterdir(), key=lambda p: p.name):
        if not child.is_dir():
            continue
        if child.name == PACKAGE:
            continue  # 自己
        if (child / "component.go").is_file():
            names.append(child.name)
    return names


def render(names: list[str]) -> str:
    prefix = module_path()
    lines = [HEADER]
    for n in names:
        lines.append(f'\t_ "{prefix}/{MODULE_ROOT}/{n}"\n')
    lines.append(FOOTER)
    return "".join(lines)


def extract_registered(text: str) -> list[str]:
    """从生成结果里反解出模块名，用于 --check 时给出人话差异。"""
    prefix = f'_ "{module_path()}/{MODULE_ROOT}/'
    out = []
    for line in text.splitlines():
        line = line.strip()
        if line.startswith(prefix):
            out.append(line[len(prefix) : -1])
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description="生成 modules/all/all.go")
    ap.add_argument("--check", action="store_true", help="只校验，不写文件；不一致时退出码 1")
    args = ap.parse_args()

    root = pathlib.Path.cwd()
    names = module_dirs(root)
    if not names:
        raise SystemExit(f"{MODULE_ROOT}/ 下没有找到任何带 component.go 的模块")

    want = render(names)
    path = root / OUTPUT
    current = path.read_text(encoding="utf-8") if path.is_file() else None

    if args.check:
        if current == want:
            print(f"OK  {OUTPUT} 已是最新（{len(names)} 个模块：{', '.join(names)}）")
            return 0
        have = extract_registered(current) if current else []
        missing = [n for n in names if n not in have]
        extra = [n for n in have if n not in names]
        print(f"FAIL {OUTPUT} 不是最新的", file=sys.stderr)
        if missing:
            print(f"     缺少：{', '.join(missing)}", file=sys.stderr)
        if extra:
            print(f"     多余：{', '.join(extra)}", file=sys.stderr)
        print("     请执行：python scripts/gen_module_imports.py", file=sys.stderr)
        return 1

    path.parent.mkdir(parents=True, exist_ok=True)
    if current == want:
        print(f"未变化 {OUTPUT}（{len(names)} 个模块）")
        return 0
    path.write_text(want, encoding="utf-8", newline="\n")
    print(f"已写入 {OUTPUT}（{len(names)} 个模块：{', '.join(names)}）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
